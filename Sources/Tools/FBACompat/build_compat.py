"""Builds Full Body Awareness versions of 1st-person animations (the FBA Compatibility folder).

1. Every kf is offered to the merge (fba_merge.py): 3rd-person legs and root motion under our upper
   body. Groups it does not recognise keep their own legs, with a warning. Arm overlays (kfs keying
   no leg bone, like the shield and torch arms) are left out.
2. Every kf with a chest gets the forward chest lean (fba_posture.py), merged ones included.

Hands come from FBA's First Person Hands patch: vanilla 1st-person hand meshes back, and FBA's own
animations converted to the 1st-person fingers (fba_fingers.py builds the same kind of package).

Always starts from the originals, so re-running never stacks anything, and refuses animations that
are already converted. Everything is built in a temporary folder and only copied to the output at
the end, so a build that fails or is closed halfway leaves the output as it was. Converting
ReAnimation's own set also writes ReAnimation_FBA_Compatibility.txt, which tells its scripts the
patch is installed, next to the output's Animations folder.

Parameters not given on the command line are asked for with their default pre-filled (Enter keeps
it); without a console the defaults are used.

Usage: python3 build_compat.py [-y] [-v] [--fba DIR] [--anims DIR] [--out DIR] [--lean DEG]
                               [--hip-motion 0..1] [--sway 0..1] [--idle-when-feet-lift y/n]
                               [--strafing-speed-fix y/n] [--alias PATTERN=NAME ...]
See README.md next to this file.
"""
import argparse
import math
import os
import re
import shutil
import sys
import tempfile

import fba_merge
import fba_posture
import nifkf
import params
from params import ask, yes_no

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
# Defaults: this mod's animations ("00 Core"), its FBA Compatibility patch beside them ("01 FBA
# Compatibility", one of the installer's options), FBA as installed here.
SRC = os.path.join(MOD, '00 Core', 'Animations', 'xbase_anim.1st')
OUT = os.path.join(MOD, '01 FBA Compatibility', 'Animations', 'xbase_anim.1st')
REFERENCE = 'x2cIdle.kf'  # check_all's rig pose; builds pick one themselves (find_reference)
# In the patch's data folder, it tells ReAnimation's scripts the patch is installed.
MARKER = 'ReAnimation_FBA_Compatibility.txt'
# A data folder with one of these is ReAnimation's own, so its converted set gets the MARKER.
REANIMATION_SCRIPTS = ('ReAnimation_v3.omwscripts', 'ReAnimation_API.omwscripts')

REFERENCE_BONES = fba_merge.LOWER_BONES + ['Bip01 Spine1', 'Bip01 Spine2', 'Bip01 Neck', 'Bip01 Head']


def kf_names(folder):
    return sorted(n for n in os.listdir(folder) if n.lower().endswith('.kf'))


def reanimation_kfs():
    """ReAnimation's own kfs, when this script still sits next to them."""
    return kf_names(SRC) if os.path.isdir(SRC) else []


def data_root(folder):
    """The data folder an .../Animations/xbase_anim.1st folder is in, or None for any other folder."""
    head, model = os.path.split(os.path.normpath(os.path.abspath(folder)))
    root, animations = os.path.split(head)
    return root if (model.lower(), animations.lower()) == ('xbase_anim.1st', 'animations') else None


def same_folder(a, b):
    return os.path.normcase(os.path.realpath(a)) == os.path.normcase(os.path.realpath(b))


def marker_text(lean, hip, sway, idle, strafe, aliases):
    return '''ReAnimation - Full Body Awareness compatibility

ReAnimation's 1st-person animations with the legs, pelvis and root motion of the 3rd-person
animations OpenMW Full Body Awareness (FBA) plays in 1st person, so the body walks, runs and lunges
with them.

For correct hands also install FBA's First Person Hands patch, from FBA's mod page: FBA replaces the
1st-person hand, glove and gauntlet meshes with 3rd-person ones made for a different finger rig, and
the patch puts the 1st-person ones back and converts FBA's own animations to their fingers.

Install: add this folder as a data directory AFTER ReAnimation's 00 Core (and after FBA). Only use
it together with OpenMW Full Body Awareness.

Camera tweaks for a visible body (look-down camera offset, hand tilt limit) live in Dynamic
Camera's settings, under Full Body Awareness Tweaks.

The presence of this file is also what tells ReAnimation's scripts that it is installed.

Generated by ReAnimation's Sources/Tools/FBACompat/build_compat.py: chest lean %g deg, hip motion
%g, spine swing %g, idle legs where feet lift: %s, strafing speed fix: %s%s.
''' % (lean, hip, sway, 'yes' if idle else 'no', 'yes' if strafe else 'no',
       ''.join('; alias %s -> %s' % pair for pair in aliases))


def find_file(folder, name):
    """Case-insensitive search for name under folder."""
    for root, _, files in os.walk(folder):
        for f in files:
            if f.lower() == name.lower():
                return os.path.join(root, f)
    return None


def find_reference(folder, names):
    """The rig's pose for bones a kf does not key: the first kf keying the whole spine and legs - in
    the set being converted, or else in ReAnimation's own, which is on the same 1st-person skeleton
    (MAGIC's spell animations key everything but Bip01)."""
    for where, candidates in ((folder, names), (SRC, reanimation_kfs())):
        for name in candidates:
            kf = nifkf.KF.load(os.path.join(where, name))
            if all(b in kf.bone_data and kf.data(b).trans['keys'] and (kf.data(b).quat_keys or kf.data(b).xyz)
                   for b in REFERENCE_BONES):
                return (name if where == folder else "ReAnimation's " + name), kf
    sys.exit('No kf in %s keys the whole spine and legs - is that an Animations/xbase_anim.1st folder?' % folder)


LEAN = 15.0
HIP_MOTION = 0.5
SWAY = 0.33
IDLE_WHEN_FEET_LIFT = True
STRAFING_SPEED_FIX = True


def alias(text):
    """PATTERN=NAME for --alias: a regular expression on our group names and what it becomes."""
    pattern, sep, name = text.partition('=')
    if not sep or not pattern:
        raise argparse.ArgumentTypeError('expected PATTERN=NAME, got %r' % text)
    try:
        re.compile(pattern)
    except re.error as e:
        raise argparse.ArgumentTypeError('%r: %s' % (pattern, e))
    return pattern, name


def parameters():
    p = argparse.ArgumentParser(
        description='Builds the FBA Compatibility patch (01 FBA Compatibility). Settings not given here are asked '
                    'for, with the default filled in (Enter keeps it).')
    p.add_argument('-y', '--yes', action='store_true', help='use the defaults for everything not given, no questions')
    p.add_argument('-v', '--verbose', action='store_true', help='print per-group detail while building')
    p.add_argument('--fba', metavar='DIR', help="FBA's folder (has meshes/xbase_anim.1st.kf)")
    p.add_argument('--anims', metavar='DIR', help='1st-person animations to convert')
    p.add_argument('--out', metavar='DIR', help='where the converted animations go')
    p.add_argument('--lean', metavar='DEG', type=float, help='extra forward chest lean (default %g)' % LEAN)
    p.add_argument('--hip-motion', metavar='0..1', type=float,
                   help='share of the attack hip lunge kept (default %g)' % HIP_MOTION)
    p.add_argument('--sway', metavar='0..1', type=float, help='share of the walk/run hip swing kept (default %g)' % SWAY)
    p.add_argument('--idle-when-feet-lift', metavar='y/n', type=yes_no,
                   help='idle legs where FBA lifts both feet (default %s)' % ('y' if IDLE_WHEN_FEET_LIFT else 'n'))
    p.add_argument('--strafing-speed-fix', metavar='y/n', type=yes_no,
                   help='half-speed 1st-person part on quick-stepping strafes (default %s)'
                        % ('y' if STRAFING_SPEED_FIX else 'n'))
    p.add_argument('--alias', metavar='PATTERN=NAME', type=alias, action='append', default=[],
                   help='rename our groups before finding their 3rd-person legs, e.g. "katar=hh" '
                        '(regular expression, repeatable, applied in order)')
    a = p.parse_args()
    params.USE_DEFAULTS = a.yes
    params.keep_console_open()
    fba_merge.VERBOSE = a.verbose
    fba = ask(a.fba, 'FBA folder', 'The one with meshes/xbase_anim.1st.kf.', params.find_fba, str)
    anims = ask(a.anims, 'Animations to convert', "ReAnimation's 00 Core/Animations/xbase_anim.1st folder.", SRC, str)
    out = ask(a.out, 'Output folder', 'Load its data folder after ReAnimation and FBA.', OUT, str)
    lean = ask(a.lean, 'Chest lean (degrees)',
               "Leans the chest forward so it doesn't fill the view when looking down.", LEAN, float)
    hip = ask(a.hip_motion, 'Hip motion during attacks (0.0 - 1.0)',
              "Share of FBA's hip lunge kept. Below 1.0 steps shorten to match; if feet glitch, use 1.0.",
              HIP_MOTION, float)
    sway = ask(a.sway, 'Hip swing while moving (0.0 - 1.0)',
               'Share of the walk/run hip swing passed to the upper body.', SWAY, float)
    idle = ask(a.idle_when_feet_lift, 'Idle legs where FBA lifts both feet (y/n)',
               'Keeps the crossbow reload from becoming a mid-air squat.', IDLE_WHEN_FEET_LIFT, yes_no)
    strafe = ask(a.strafing_speed_fix, 'Strafing animation speed fix (y/n)',
                 "Leaves the 3rd-person strafe alone. Those step quickly (FBA's run strafes take half the "
                 "stride of its forward run, so the game plays them twice as fast), and the 1st-person "
                 "part swung along at the same pace; this makes it swing half as often - one 1st-person "
                 "step to two of the legs' - wherever a strafe's stride is 2/3 of the forward one or less. "
                 "The footstep sounds stay on the legs' steps.", STRAFING_SPEED_FIX, yes_no)
    for name, value in (('hip motion', hip), ('spine swing', sway)):
        if not 0.0 <= value <= 1.0:
            sys.exit('%s must be between 0.0 and 1.0, got %s' % (name, value))
    return fba, anims, out, lean, hip, sway, idle, strafe, a.alias


def main():
    fba, anims, out, lean, hip, sway, idle, strafe, aliases = parameters()
    meshes = params.child(fba, 'meshes')
    third_person = (meshes and params.child(meshes, 'xbase_anim.1st.kf')) or find_file(fba, 'xbase_anim.1st.kf')
    if third_person is None:
        sys.exit('No xbase_anim.1st.kf under %s - is that the FBA folder?' % fba)
    if same_folder(anims, out):
        sys.exit('The output folder is the folder being converted: give the converted animations '
                 'a folder of their own (--out).')
    source_root = data_root(anims)
    if source_root and params.child(source_root, MARKER):
        sys.exit('%s has %s: the animations there are already converted (a built patch, or a mod '
                 "manager's ReAnimation with the FBA option ticked). Convert the originals: the "
                 "downloaded archive's 00 Core/Animations/xbase_anim.1st." % (source_root, MARKER))
    fba_posture.TILT = math.radians(lean)
    fba_merge.HIP_MOTION = hip
    fba_merge.SWAY = sway
    fba_merge.IDLE_WHEN_FEET_LIFT = idle
    fba_merge.STRAFE_SPEED_FIX = strafe
    fba_merge.ALIASES = aliases

    names = kf_names(anims)
    reference_name, reference = find_reference(anims, names)
    print('\nFBA animations from %s' % third_person)
    print('rig pose from %s; lean %.1f deg, hip motion %.2f, spine swing %.2f, idle legs where feet lift: %s, '
          'strafing speed fix: %s%s'
          % (reference_name, lean, hip, sway, 'yes' if idle else 'no', 'yes' if strafe else 'no',
             ''.join('; %s -> %s' % pair for pair in aliases)))

    merged = set()
    written = []
    with tempfile.TemporaryDirectory(prefix='fba_compat_') as build_dir:
        for i, name in enumerate(names, 1):
            fba_merge.info('== merge ' + name)
            segments = fba_merge.build(os.path.join(anims, name), third_person, os.path.join(build_dir, name),
                                       reference)
            if segments is not None:
                if fba_merge.VERBOSE:
                    fba_merge.report(segments)
                merged.add(name)
            if not fba_merge.VERBOSE:
                print('%3d/%d  %s' % (i, len(names), name))

        leaned = 0
        for name in names:
            kf = nifkf.KF.load(os.path.join(build_dir if name in merged else anims, name))
            changed = False
            if fba_posture.has_chest(kf):
                fallbacks = fba_posture.lean(kf, reference)
                if fallbacks:
                    fba_merge.info('   %s: %s from %s' % (name, ', '.join(fallbacks), reference_name))
                leaned += 1
                changed = True
            else:
                fba_merge.info('   does not rotate the chest, not leaned: ' + name)
            if changed or name in merged:
                kf.save(os.path.join(build_dir, name))
                written.append(name)

        # Only now does the output change.
        os.makedirs(out, exist_ok=True)
        for name in written:
            shutil.copyfile(os.path.join(build_dir, name), os.path.join(out, name))
    print('merged %d of %d kfs, leaned %d by %.1f deg, %d written to %s'
          % (len(merged), len(names), leaned, lean, len(written), out))

    # Left by an earlier build: removed from this mod's own patch folder, only listed anywhere else.
    made = {n.lower() for n in written}
    stale = [n for n in kf_names(out) if n.lower() not in made]
    if stale and same_folder(out, OUT):
        for name in stale:
            os.remove(os.path.join(out, name))
        print('removed %d kfs an earlier build left, which this one no longer makes: %s' % (len(stale), ', '.join(stale)))
    elif stale:
        print('\nnot made by this build, left in the output folder (delete them if an earlier build made them): '
              + ', '.join(stale))

    if source_root and any(params.child(source_root, n) for n in REANIMATION_SCRIPTS):
        out_root = data_root(out)
        if out_root:
            with open(os.path.join(out_root, MARKER), 'w', encoding='utf-8', newline='\n') as f:
                f.write(marker_text(lean, hip, sway, idle, strafe, aliases))
            print('wrote %s' % os.path.join(out_root, MARKER))
        else:
            print('\nReAnimation knows the patch is installed by a %s next to its Animations folder; this output is '
                  'not an Animations/xbase_anim.1st folder, so put one there yourself (01 FBA Compatibility has '
                  'it).' % MARKER)
    if fba_merge.WARNINGS:
        print('\n%d warnings - left as they were:' % len(fba_merge.WARNINGS))
        for w in fba_merge.WARNINGS:
            print('  ' + w)


if __name__ == '__main__':
    main()
